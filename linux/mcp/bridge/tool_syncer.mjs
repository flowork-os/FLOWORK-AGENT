import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { McpClientManager } from '../client/index.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const SCRIPT_DIR = path.resolve(__dirname, '..');
const PROJECT_ROOT = path.resolve(SCRIPT_DIR, '..');

export class McpToolSyncer {
  constructor(options = {}) {
    this.projectRoot = options.projectRoot || PROJECT_ROOT;
    this.toolsDir = path.join(this.projectRoot, 'tools');
    this.manager = new McpClientManager({ projectRoot: this.projectRoot });
  }

  /**
   * Translates JSON Schema properties from MCP into Flowork manifest parameter format
   */
  mapInputSchemaToParameters(inputSchema) {
    const parameters = {};
    if (!inputSchema || typeof inputSchema !== 'object') return parameters;

    const properties = inputSchema.properties || {};
    const requiredList = Array.isArray(inputSchema.required) ? inputSchema.required : [];

    for (const [key, prop] of Object.entries(properties)) {
      let type = 'STRING';
      if (prop.type === 'number' || prop.type === 'integer') type = 'INTEGER';
      else if (prop.type === 'boolean') type = 'BOOLEAN';
      else if (prop.type === 'object') type = 'OBJECT';
      else if (prop.type === 'array') type = 'ARRAY';

      parameters[key] = {
        description: prop.description || `Parameter ${key}`,
        type,
        required: requiredList.includes(key)
      };
    }

    return parameters;
  }

  /**
   * Syncs active MCP tools into Flowork tools/ registry
   */
  async syncTools() {
    console.log('[MCP Syncer] 🔍 Discovering tools across configured MCP servers...');
    const catalog = await this.manager.listAllTools();
    console.log(`[MCP Syncer] Found ${catalog.length} tools across servers.`);

    let syncedCount = 0;

    for (const tool of catalog) {
      // Do not duplicate internal canvas sidecars that already have native routing
      if (tool.server === 'canvas-legacy') continue;

      const safeServer = tool.server.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
      const safeTool = tool.name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
      const toolFolder = `mcp_${safeServer}_${safeTool}`;
      const targetDir = path.join(this.toolsDir, toolFolder);

      if (!fs.existsSync(targetDir)) {
        fs.mkdirSync(targetDir, { recursive: true });
      }

      // 1. Build manifest.json
      const manifest = {
        name: toolFolder,
        title: `MCP [${tool.server}] ${tool.name}`,
        description: tool.description || `Tool ${tool.name} hosted by MCP server ${tool.server}.`,
        category: 'mcp_integration',
        author: `MCP Server (${tool.server})`,
        version: '1.0.0',
        command: `node mcp/run.mjs --call ${tool.server} ${tool.name}`,
        entry: 'main.mjs',
        mcp_meta: {
          server: tool.server,
          original_name: tool.name
        },
        keywords: [
          'mcp',
          tool.server,
          tool.name,
          'tool',
          'model_context_protocol',
          'integration'
        ],
        parameters: this.mapInputSchemaToParameters(tool.inputSchema)
      };

      fs.writeFileSync(path.join(targetDir, 'manifest.json'), JSON.stringify(manifest, null, 2), 'utf8');

      // 2. Build executable proxy main.mjs
      const runnerCode = `#!/usr/bin/env node
// 🔌 Flowork OS MCP Proxy Tool: ${toolFolder}
// Auto-generated by Sovereign MCP Bridge Syncer
// Target: Server [${tool.server}] -> Tool [${tool.name}]

import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..', '..');
const mcpRunner = path.join(projectRoot, 'mcp', 'run.mjs');

function parseArgs() {
  const args = process.argv.slice(2);
  let params = {};
  const pIdx = args.indexOf('--params');
  if (pIdx !== -1 && args[pIdx + 1]) {
    try { params = JSON.parse(args[pIdx + 1]); } catch (_) {}
  } else if (args[0] && args[0].startsWith('{')) {
    try { params = JSON.parse(args[0]); } catch (_) {}
  }
  return params;
}

const params = parseArgs();
const res = spawnSync('node', [
  mcpRunner,
  '--call',
  '${tool.server}',
  '${tool.name}',
  JSON.stringify(params)
], {
  encoding: 'utf8',
  timeout: 30000
});

if (res.stdout) {
  process.stdout.write(res.stdout);
}
if (res.stderr) {
  process.stderr.write(res.stderr);
}

process.exit(res.status || 0);
`;

      fs.writeFileSync(path.join(targetDir, 'main.mjs'), runnerCode, 'utf8');
      try {
        fs.chmodSync(path.join(targetDir, 'main.mjs'), 0o755);
      } catch (_) {}

      syncedCount++;
    }

    await this.manager.closeAll();
    console.log(`[MCP Syncer] ✅ Successfully synchronized ${syncedCount} external MCP tools into Flowork registry (${this.toolsDir}).`);
    return syncedCount;
  }
}

// CLI Execution entrypoint
if (process.argv[1] && process.argv[1].endsWith('tool_syncer.mjs')) {
  const syncer = new McpToolSyncer();
  syncer.syncTools().then(() => {
    process.exit(0);
  }).catch((err) => {
    console.error('[MCP Syncer Error]', err.message);
    process.exit(1);
  });
}
